/**
 * Shared contracts between the server and the web client.
 *
 * The single most important rule in this codebase: the only thing that ever travels
 * between teacher and student is a `Segment.id`. Never a DOM range, never a character
 * offset, never a scroll position. A segment id survives differences in font size,
 * screen width, device and visible text layer, which is what makes one teacher's click
 * land correctly on thirty different phones.
 */

// ---------------------------------------------------------------------------
// Text model
// ---------------------------------------------------------------------------

/**
 * What a segment is structurally. Drives rendering (verse is indented and set apart,
 * outline headings anchor navigation) and nothing else — sync treats all kinds alike.
 */
export type SegmentKind =
  | 'title' // opening ornament and the name of the text
  | 'homage' // the opening salutation
  | 'outline' // sa bcad: "explained in three parts", "first, ...", "second, ..."
  | 'prose' // ordinary commentary prose
  | 'verse' // quoted root text, usually metrical
  | 'colophon'

/**
 * How strongly a segment is separated from the one after it.
 *
 * Tibetan marks a minor break with a single shad (U+0F0D) and a major one with a pair of
 * them. The pipeline reports which it found; the reader uses it for paragraph spacing
 * that matches the printed page.
 */
export type BreakStrength = 'minor' | 'major'

export interface Segment {
  /**
   * Stable and opaque. Owned by the content pipeline, never generated by this app, and
   * adopted exactly as given — so room logs stay valid across re-imports.
   *
   * This is the only identifier exposed over the wire or written to a room log. Treat
   * it as meaningless: do not parse it, sort by it, or infer order from it. Order is
   * `idx`.
   */
  id: string
  /** Display order. Safe to renumber freely — nothing external references it. */
  idx: number
  kind: SegmentKind
  /** The Tibetan text of this segment, including its trailing shad. */
  bo: string
  breakAfter: BreakStrength
  /**
   * Scriptural reference carried by this segment — the chapter or folio a quotation
   * comes from, as the pipeline extracted it from the bracket marks (U+0F3C, U+0F3D).
   *
   * Metadata for search and navigation only. The bracketed reference is left in place
   * inside `bo`, where the printed edition puts it, so a reader that renders this field
   * as well would show the citation twice.
   */
  cite?: string
  // Layers. All null until translations exist; adding them later needs no schema or
  // protocol change, because the client highlights by id regardless of what it renders.
  wylie?: string
  en?: string
  note?: string
}

export interface TextMeta {
  id: string
  slug: string
  titleBo: string
  titleEn?: string
  /** Which provider supplied this text. */
  source: 'api' | 'fixture'
}

export interface SegmentedText {
  meta: TextMeta
  segments: Segment[]
}

/**
 * The seam between this app and wherever texts actually live.
 *
 * Texts are produced by a separate content pipeline and served by the WeBuddhist content
 * API. `ApiTextProvider` is the real implementation; `FixtureTextProvider` reads JSON
 * from the gitignored `texts/` directory so development can proceed before the API
 * exists, without any corpus entering this repo.
 *
 * Whichever provider is used, its output is imported into Postgres once. Rooms and sync
 * read only from Postgres, so a provider is never on the path of a live class.
 */
export interface TextProvider {
  listTexts(): Promise<TextMeta[]>
  getText(slug: string): Promise<SegmentedText>
}

// ---------------------------------------------------------------------------
// Rooms
// ---------------------------------------------------------------------------

/**
 * Room code alphabet, chosen so a code read off a whiteboard from the back of a room
 * is unambiguous: no O/0, no I/1/l, no S/5 confusion in common classroom fonts.
 */
export const ROOM_CODE_ALPHABET = 'ABCDEFGHJKMNPQRSTUVWXYZ23456789'
export const ROOM_CODE_LENGTH = 6

export interface RoomState {
  code: string
  textSlug: string
  /** Null before the teacher has selected anything. */
  currentSegmentId: string | null
  participantCount: number
}

// ---------------------------------------------------------------------------
// Socket protocol
// ---------------------------------------------------------------------------

/**
 * Events the client sends. `teach:goto` carries the host token and is rejected
 * server-side unless it matches the room's stored hash — the teacher-only UI is a
 * convenience, not the security boundary.
 */
export interface ClientToServerEvents {
  'room:join': (
    payload: { code: string; displayName: string },
    ack: (result: { ok: true; state: RoomState } | { ok: false; error: string }) => void,
  ) => void
  'teach:goto': (
    payload: { segmentId: string; hostToken: string },
    ack: (result: { ok: true } | { ok: false; error: string }) => void,
  ) => void
  /**
   * End the class. The room stops accepting joins and everyone present is told.
   * Host-only, checked the same way as `teach:goto`.
   */
  'room:close': (
    payload: { hostToken: string },
    ack: (result: { ok: true } | { ok: false; error: string }) => void,
  ) => void
}

export interface ServerToClientEvents {
  /** Authoritative snapshot. Sent on join and on reconnect; overrides local state. */
  'room:state': (state: RoomState) => void
  /** Incremental move. Applied optimistically for responsiveness. */
  'teach:goto': (payload: { segmentId: string }) => void
  presence: (payload: { count: number }) => void
  'room:closed': () => void
}
